"""
FleetFlow Stream Processing Service

Real-time event detection using Complex Event Processing (CEP) patterns:
- Late driver detection
- Order hotspot detection
- Traffic jam alerts
- Route deviation detection

This is a simplified Python implementation. Production would use Apache Flink.
"""

import asyncio
import json
from datetime import datetime, timedelta
from typing import Optional, Callable, Any
from collections import defaultdict
from dataclasses import dataclass, field
from confluent_kafka import Consumer, Producer, KafkaError
import structlog

logger = structlog.get_logger()


@dataclass
class DriverState:
    """Current state of a driver."""
    driver_id: str
    latitude: float = 0.0
    longitude: float = 0.0
    speed_kmh: float = 0.0
    last_update: datetime = field(default_factory=datetime.utcnow)
    current_route_id: Optional[str] = None
    expected_eta: Optional[datetime] = None
    stops_completed: int = 0
    stops_total: int = 0


@dataclass
class Alert:
    """Alert generated by CEP."""
    alert_type: str
    severity: str  # 'low', 'medium', 'high', 'critical'
    driver_id: Optional[str]
    route_id: Optional[str]
    message: str
    data: dict
    timestamp: datetime = field(default_factory=datetime.utcnow)


class EventWindow:
    """Time-based sliding window for event aggregation."""
    
    def __init__(self, window_size_seconds: int = 300):
        self.window_size = timedelta(seconds=window_size_seconds)
        self.events: list[tuple[datetime, Any]] = []
    
    def add(self, event: Any) -> None:
        """Add event to window."""
        now = datetime.utcnow()
        self.events.append((now, event))
        self._cleanup()
    
    def _cleanup(self) -> None:
        """Remove expired events."""
        cutoff = datetime.utcnow() - self.window_size
        self.events = [(ts, e) for ts, e in self.events if ts > cutoff]
    
    def count(self) -> int:
        """Get event count in window."""
        self._cleanup()
        return len(self.events)
    
    def get_events(self) -> list[Any]:
        """Get all events in window."""
        self._cleanup()
        return [e for _, e in self.events]


class StreamProcessor:
    """
    Real-time stream processor for FleetFlow events.
    
    Implements CEP patterns for:
    1. Late driver detection - driver won't make ETA
    2. Hotspot detection - surge of orders in an area
    3. Traffic alerts - significant slowdowns
    4. Route deviation - driver off planned route
    """
    
    def __init__(
        self,
        kafka_bootstrap_servers: str = "localhost:9092",
        consumer_group: str = "fleetflow-stream-processor"
    ):
        self.bootstrap_servers = kafka_bootstrap_servers
        self.consumer_group = consumer_group
        
        # State management
        self.driver_states: dict[str, DriverState] = {}
        self.order_windows: dict[str, EventWindow] = defaultdict(lambda: EventWindow(900))  # 15 min
        self.traffic_windows: dict[str, EventWindow] = defaultdict(lambda: EventWindow(300))  # 5 min
        
        # Alert handlers
        self.alert_handlers: list[Callable[[Alert], None]] = []
        
        # Kafka clients
        self._consumer: Optional[Consumer] = None
        self._producer: Optional[Producer] = None
        self._running = False
    
    def add_alert_handler(self, handler: Callable[[Alert], None]) -> None:
        """Register alert handler."""
        self.alert_handlers.append(handler)
    
    def _emit_alert(self, alert: Alert) -> None:
        """Emit alert to all handlers and Kafka."""
        for handler in self.alert_handlers:
            try:
                handler(alert)
            except Exception as e:
                logger.error("Alert handler failed", error=str(e))
        
        # Publish to Kafka
        if self._producer:
            topic = f"alerts.{alert.alert_type}"
            self._producer.produce(
                topic=topic,
                key=alert.driver_id or "system",
                value=json.dumps({
                    "alert_type": alert.alert_type,
                    "severity": alert.severity,
                    "driver_id": alert.driver_id,
                    "route_id": alert.route_id,
                    "message": alert.message,
                    "data": alert.data,
                    "timestamp": alert.timestamp.isoformat(),
                }).encode('utf-8')
            )
    
    # ====================================
    # CEP Pattern: Late Driver Detection
    # ====================================
    
    def _check_late_driver(self, driver_id: str, location: dict) -> None:
        """
        Detect if driver will be late to next stop.
        
        Pattern: If current distance to next stop > (time_remaining * avg_speed)
        """
        state = self.driver_states.get(driver_id)
        if not state or not state.expected_eta:
            return
        
        time_remaining = (state.expected_eta - datetime.utcnow()).total_seconds() / 60
        if time_remaining <= 0:
            return
        
        # Estimate distance (simplified - would use routing API)
        lat1, lon1 = state.latitude, state.longitude
        lat2, lon2 = location.get('latitude', lat1), location.get('longitude', lon1)
        distance_km = self._haversine(lat1, lon1, lat2, lon2)
        
        # If >5km away with <15min remaining at <30km/h, likely late
        avg_speed = max(state.speed_kmh, 20)
        estimated_time_minutes = (distance_km / avg_speed) * 60
        
        if distance_km > 3 and estimated_time_minutes > time_remaining + 5:
            self._emit_alert(Alert(
                alert_type="driver_late",
                severity="medium",
                driver_id=driver_id,
                route_id=state.current_route_id,
                message=f"Driver {driver_id} estimated {int(estimated_time_minutes - time_remaining)} min late",
                data={
                    "distance_km": round(distance_km, 2),
                    "time_remaining_minutes": round(time_remaining, 1),
                    "estimated_arrival_minutes": round(estimated_time_minutes, 1),
                }
            ))
    
    # ====================================
    # CEP Pattern: Hotspot Detection
    # ====================================
    
    def _check_hotspot(self, order_event: dict) -> None:
        """
        Detect order hotspots (surge in specific area).
        
        Pattern: >10 orders in a 1km radius within 15 minutes
        """
        import h3
        
        lat = order_event.get('latitude', 0)
        lon = order_event.get('longitude', 0)
        
        # Get H3 cell at resolution 8 (~460m radius)
        h3_cell = h3.geo_to_h3(lat, lon, 8)
        
        self.order_windows[h3_cell].add(order_event)
        count = self.order_windows[h3_cell].count()
        
        if count >= 10:
            self._emit_alert(Alert(
                alert_type="hotspot",
                severity="high",
                driver_id=None,
                route_id=None,
                message=f"Order hotspot detected: {count} orders in 15min",
                data={
                    "h3_cell": h3_cell,
                    "order_count": count,
                    "center_lat": lat,
                    "center_lon": lon,
                }
            ))
    
    # ====================================
    # CEP Pattern: Traffic Alert
    # ====================================
    
    def _check_traffic(self, traffic_event: dict) -> None:
        """
        Detect significant traffic slowdowns.
        
        Pattern: Speed < 30% of free flow for >5 minutes
        """
        segment_id = traffic_event.get('segment_id')
        current_speed = traffic_event.get('current_speed_kmh', 0)
        free_flow = traffic_event.get('free_flow_speed_kmh', 60)
        
        if free_flow <= 0:
            return
        
        congestion = current_speed / free_flow
        
        self.traffic_windows[segment_id].add({
            'congestion': congestion,
            'speed': current_speed,
        })
        
        events = self.traffic_windows[segment_id].get_events()
        if len(events) >= 5:
            avg_congestion = sum(e['congestion'] for e in events) / len(events)
            
            if avg_congestion < 0.3:  # Less than 30% of normal speed
                self._emit_alert(Alert(
                    alert_type="traffic_jam",
                    severity="high",
                    driver_id=None,
                    route_id=None,
                    message=f"Severe traffic on segment {segment_id}",
                    data={
                        "segment_id": segment_id,
                        "avg_speed_kmh": round(current_speed, 1),
                        "congestion_level": round(avg_congestion, 2),
                        "duration_minutes": 5,
                    }
                ))
    
    # ====================================
    # Event Handlers
    # ====================================
    
    def _handle_gps_event(self, event: dict) -> None:
        """Handle GPS location update."""
        driver_id = event.get('driver_id')
        if not driver_id:
            return
        
        location = event.get('location') or {}
        latitude = event.get('latitude', location.get('latitude'))
        longitude = event.get('longitude', location.get('longitude'))

        # Update driver state
        if driver_id not in self.driver_states:
            self.driver_states[driver_id] = DriverState(driver_id=driver_id)
        
        state = self.driver_states[driver_id]
        if latitude is not None:
            state.latitude = latitude
        if longitude is not None:
            state.longitude = longitude
        state.speed_kmh = event.get('speed_kmh', state.speed_kmh)
        state.last_update = datetime.utcnow()
        
        # Check for late driver
        self._check_late_driver(driver_id, {
            'latitude': state.latitude,
            'longitude': state.longitude,
        })
    
    def _handle_order_event(self, event: dict) -> None:
        """Handle new order event."""
        # Check for hotspot
        address = event.get('delivery_address', {})
        location = address.get('location', {})
        if location:
            self._check_hotspot({
                'latitude': location.get('latitude', 0),
                'longitude': location.get('longitude', 0),
                'order_id': event.get('order_id'),
            })
    
    def _handle_traffic_event(self, event: dict) -> None:
        """Handle traffic update."""
        self._check_traffic(event)
    
    def _handle_route_event(self, event: dict) -> None:
        """Handle route assignment."""
        driver_id = event.get('driver_id')
        if driver_id and driver_id in self.driver_states:
            state = self.driver_states[driver_id]
            state.current_route_id = event.get('route_id')
            state.stops_total = len(event.get('stops', []))
    
    # ====================================
    # Main Processing Loop
    # ====================================
    
    async def start(self) -> None:
        """Start the stream processor."""
        self._consumer = Consumer({
            'bootstrap.servers': self.bootstrap_servers,
            'group.id': self.consumer_group,
            'auto.offset.reset': 'latest',
        })
        
        self._producer = Producer({
            'bootstrap.servers': self.bootstrap_servers,
        })
        
        topics = [
            'gps.location',
            'orders.created',
            'traffic.updates',
            'routes.created',
        ]
        self._consumer.subscribe(topics)
        
        self._running = True
        logger.info("Stream processor started", topics=topics)
        
        try:
            while self._running:
                msg = self._consumer.poll(1.0)
                
                if msg is None:
                    continue
                if msg.error():
                    if msg.error().code() == KafkaError._PARTITION_EOF:
                        continue
                    logger.error("Kafka error", error=msg.error())
                    continue
                
                topic = msg.topic()
                try:
                    event = json.loads(msg.value().decode('utf-8'))
                    
                    if topic == 'gps.location':
                        self._handle_gps_event(event)
                    elif topic == 'orders.created':
                        self._handle_order_event(event)
                    elif topic == 'traffic.updates':
                        self._handle_traffic_event(event)
                    elif topic == 'routes.created':
                        self._handle_route_event(event)
                    
                except json.JSONDecodeError:
                    logger.warning("Invalid JSON in message", topic=topic)
                except Exception as e:
                    logger.error("Error processing event", topic=topic, error=str(e))
                
                # Flush producer periodically
                self._producer.poll(0)
                
        finally:
            self._consumer.close()
            self._producer.flush()
    
    def stop(self) -> None:
        """Stop the stream processor."""
        self._running = False
    
    @staticmethod
    def _haversine(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
        """Calculate distance in km between two points."""
        from math import radians, sin, cos, sqrt, atan2
        
        R = 6371
        lat1, lon1, lat2, lon2 = map(radians, [lat1, lon1, lat2, lon2])
        dlat = lat2 - lat1
        dlon = lon2 - lon1
        
        a = sin(dlat/2)**2 + cos(lat1) * cos(lat2) * sin(dlon/2)**2
        c = 2 * atan2(sqrt(a), sqrt(1-a))
        
        return R * c


# Main entry point
if __name__ == "__main__":
    processor = StreamProcessor()
    
    # Simple alert handler
    def log_alert(alert: Alert):
        print(f"[{alert.severity.upper()}] {alert.alert_type}: {alert.message}")
    
    processor.add_alert_handler(log_alert)
    
    asyncio.run(processor.start())
