param(
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

$root = (Resolve-Path "$PSScriptRoot\..").Path
$envFile = Join-Path $root ".env.ports"

if ((Test-Path $envFile) -and -not $Force) {
    Write-Host "Using existing $envFile"
    return
}

$usedPorts = $null
if (Get-Command Get-NetTCPConnection -ErrorAction SilentlyContinue) {
    $usedPorts = New-Object 'System.Collections.Generic.HashSet[int]'
    Get-NetTCPConnection -State Listen -ErrorAction SilentlyContinue | ForEach-Object {
        $null = $usedPorts.Add([int]$_.LocalPort)
    }
}

function Test-PortAvailable {
    param([int]$Port)
    if ($usedPorts) {
        return -not $usedPorts.Contains($Port)
    }
    try {
        $listener = [System.Net.Sockets.TcpListener]::new([System.Net.IPAddress]::Loopback, $Port)
        $listener.Start()
        $listener.Stop()
        return $true
    } catch {
        return $false
    }
}

function Get-FreePort {
    param(
        [int]$Preferred,
        [System.Collections.Generic.HashSet[int]]$Used
    )
    for ($offset = 0; $offset -le 200; $offset++) {
        $candidate = $Preferred + $offset
        if (-not $Used.Contains($candidate) -and (Test-PortAvailable -Port $candidate)) {
            $null = $Used.Add($candidate)
            return $candidate
        }
    }
    throw "No free port found near $Preferred"
}

$used = New-Object 'System.Collections.Generic.HashSet[int]'
$ports = [ordered]@{}
$ports.API_PORT = Get-FreePort -Preferred 8000 -Used $used
$ports.WS_PORT = Get-FreePort -Preferred 8002 -Used $used
$ports.FRONTEND_PORT = Get-FreePort -Preferred 3000 -Used $used
$ports.POSTGRES_PORT = Get-FreePort -Preferred 5432 -Used $used
$ports.TIMESCALE_PORT = Get-FreePort -Preferred 5433 -Used $used
$ports.REDIS_PORT = Get-FreePort -Preferred 6379 -Used $used
$ports.MONGO_PORT = Get-FreePort -Preferred 27017 -Used $used
$ports.ZOOKEEPER_PORT = Get-FreePort -Preferred 2181 -Used $used
$ports.KAFKA_PORT = Get-FreePort -Preferred 9092 -Used $used
$ports.KAFKA_INTERNAL_PORT = Get-FreePort -Preferred 29092 -Used $used
$ports.KAFKA_UI_PORT = Get-FreePort -Preferred 8080 -Used $used
$ports.AIRFLOW_PORT = Get-FreePort -Preferred 8081 -Used $used
$ports.FLINK_PORT = Get-FreePort -Preferred 8082 -Used $used
$ports.MLFLOW_PORT = Get-FreePort -Preferred 5001 -Used $used
$ports.OSRM_PORT = Get-FreePort -Preferred 5000 -Used $used

$frontendPort = $ports.FRONTEND_PORT
$apiPort = $ports.API_PORT
$wsPort = $ports.WS_PORT
$postgresPort = $ports.POSTGRES_PORT
$kafkaPort = $ports.KAFKA_PORT
$osrmPort = $ports.OSRM_PORT

$fastapiUrl = "http://localhost:$apiPort/api/v1"
$wsUrl = "ws://localhost:$wsPort/ws"
$dbUrl = "postgresql://fleetflow:fleetflow_dev@localhost:$postgresPort/fleetflow"
$kafkaBootstrap = "localhost:$kafkaPort"
$osrmApiUrl = "http://localhost:$osrmPort"
$allowedOrigins = "http://localhost:$frontendPort,http://127.0.0.1:$frontendPort"

$lines = @(
    "# Auto-generated by scripts/ports-auto.ps1",
    "API_PORT=$($ports.API_PORT)",
    "WS_PORT=$($ports.WS_PORT)",
    "FRONTEND_PORT=$($ports.FRONTEND_PORT)",
    "POSTGRES_PORT=$($ports.POSTGRES_PORT)",
    "TIMESCALE_PORT=$($ports.TIMESCALE_PORT)",
    "REDIS_PORT=$($ports.REDIS_PORT)",
    "MONGO_PORT=$($ports.MONGO_PORT)",
    "ZOOKEEPER_PORT=$($ports.ZOOKEEPER_PORT)",
    "KAFKA_PORT=$($ports.KAFKA_PORT)",
    "KAFKA_INTERNAL_PORT=$($ports.KAFKA_INTERNAL_PORT)",
    "KAFKA_UI_PORT=$($ports.KAFKA_UI_PORT)",
    "AIRFLOW_PORT=$($ports.AIRFLOW_PORT)",
    "FLINK_PORT=$($ports.FLINK_PORT)",
    "MLFLOW_PORT=$($ports.MLFLOW_PORT)",
    "OSRM_PORT=$($ports.OSRM_PORT)",
    "",
    "FASTAPI_URL=$fastapiUrl",
    "NEXT_PUBLIC_WS_URL=$wsUrl",
    "DATABASE_URL=$dbUrl",
    "KAFKA_BOOTSTRAP_SERVERS=$kafkaBootstrap",
    "OSRM_API_URL=$osrmApiUrl",
    "ALLOWED_ORIGINS=$allowedOrigins",
    "WEBSOCKET_ALLOWED_ORIGINS=$allowedOrigins"
)

Set-Content -Path $envFile -Value $lines -Encoding ascii
Write-Host "Wrote $envFile"
