#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT/.env.ports"
FORCE=0

for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
  esac
done

if [[ -f "$ENV_FILE" && $FORCE -eq 0 ]]; then
  echo "Using existing $ENV_FILE"
  exit 0
fi

is_port_free() {
  python - "$1" <<'PY'
import socket
import sys

port = int(sys.argv[1])
sock = socket.socket()
try:
    sock.bind(("127.0.0.1", port))
except OSError:
    sys.exit(1)
finally:
    sock.close()
sys.exit(0)
PY
}

USED_PORTS=()
is_used() {
  local port="$1"
  for used in "${USED_PORTS[@]}"; do
    if [[ "$used" == "$port" ]]; then
      return 0
    fi
  done
  return 1
}

pick_port() {
  local preferred="$1"
  local candidate
  for offset in $(seq 0 200); do
    candidate=$((preferred + offset))
    if ! is_used "$candidate" && is_port_free "$candidate"; then
      USED_PORTS+=("$candidate")
      echo "$candidate"
      return 0
    fi
  done
  echo "No free port found near $preferred" >&2
  return 1
}

API_PORT="$(pick_port 8000)"
WS_PORT="$(pick_port 8002)"
FRONTEND_PORT="$(pick_port 3000)"
POSTGRES_PORT="$(pick_port 5432)"
TIMESCALE_PORT="$(pick_port 5433)"
REDIS_PORT="$(pick_port 6379)"
MONGO_PORT="$(pick_port 27017)"
ZOOKEEPER_PORT="$(pick_port 2181)"
KAFKA_PORT="$(pick_port 9092)"
KAFKA_INTERNAL_PORT="$(pick_port 29092)"
KAFKA_UI_PORT="$(pick_port 8080)"
AIRFLOW_PORT="$(pick_port 8081)"
FLINK_PORT="$(pick_port 8082)"
MLFLOW_PORT="$(pick_port 5001)"
OSRM_PORT="$(pick_port 5000)"

FASTAPI_URL="http://localhost:${API_PORT}/api/v1"
NEXT_PUBLIC_WS_URL="ws://localhost:${WS_PORT}/ws"
DATABASE_URL="postgresql://fleetflow:fleetflow_dev@localhost:${POSTGRES_PORT}/fleetflow"
KAFKA_BOOTSTRAP_SERVERS="localhost:${KAFKA_PORT}"
OSRM_API_URL="http://localhost:${OSRM_PORT}"
ALLOWED_ORIGINS="http://localhost:${FRONTEND_PORT},http://127.0.0.1:${FRONTEND_PORT}"

cat > "$ENV_FILE" <<EOF
# Auto-generated by scripts/ports-auto.sh
API_PORT=${API_PORT}
WS_PORT=${WS_PORT}
FRONTEND_PORT=${FRONTEND_PORT}
POSTGRES_PORT=${POSTGRES_PORT}
TIMESCALE_PORT=${TIMESCALE_PORT}
REDIS_PORT=${REDIS_PORT}
MONGO_PORT=${MONGO_PORT}
ZOOKEEPER_PORT=${ZOOKEEPER_PORT}
KAFKA_PORT=${KAFKA_PORT}
KAFKA_INTERNAL_PORT=${KAFKA_INTERNAL_PORT}
KAFKA_UI_PORT=${KAFKA_UI_PORT}
AIRFLOW_PORT=${AIRFLOW_PORT}
FLINK_PORT=${FLINK_PORT}
MLFLOW_PORT=${MLFLOW_PORT}
OSRM_PORT=${OSRM_PORT}

FASTAPI_URL=${FASTAPI_URL}
NEXT_PUBLIC_WS_URL=${NEXT_PUBLIC_WS_URL}
DATABASE_URL=${DATABASE_URL}
KAFKA_BOOTSTRAP_SERVERS=${KAFKA_BOOTSTRAP_SERVERS}
OSRM_API_URL=${OSRM_API_URL}
ALLOWED_ORIGINS=${ALLOWED_ORIGINS}
WEBSOCKET_ALLOWED_ORIGINS=${ALLOWED_ORIGINS}
EOF

echo "Wrote $ENV_FILE"
